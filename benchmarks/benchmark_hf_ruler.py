"""Run an official NVIDIA RULER JSONL split with a real HF causal LM.

Each record is generated by RULER's ``scripts/data/prepare.py`` and contains
``input``/``outputs``.  The benchmark runs the unpatched teacher and the QCC
retrofit separately, scores exact answer-string containment, and records
per-record errors.  It is intentionally conservative: OOM, context-limit,
and generation failures are reported as failures rather than dropped.
"""

from __future__ import annotations

import argparse
import gc
import json
import sys
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from qcc_transformer import patch_hf_model, reset_hf_qcc_cache
from qcc_transformer.hybrid_archive import load_hybrid_retrofit_adapter
from qcc_transformer.hf_loading import load_hf_causal_lm, model_input_device
from qcc_transformer.production_profile import enable_qkv_only_deployment_profile


def native_context(config) -> int | None:
    values = [
        getattr(config, name, None)
        for name in ("max_position_embeddings", "n_positions", "max_sequence_length")
    ]
    values = [int(value) for value in values if isinstance(value, int) and value > 0]
    return max(values) if values else None


def length_bucket(tokens: int) -> str:
    if tokens < 8_192:
        return "0-8K"
    if tokens < 32_768:
        return "8-32K"
    if tokens < 128_000:
        return "32-128K"
    return "128K+"


def _records(path: Path, max_examples: int | None):
    count = 0
    with path.open("r", encoding="utf-8") as stream:
        for line_number, line in enumerate(stream, 1):
            if max_examples is not None and count >= max_examples:
                break
            if not line.strip():
                continue
            record = json.loads(line)
            if not isinstance(record, dict) or not isinstance(record.get("input"), str):
                raise ValueError(f"line {line_number}: RULER record needs string input")
            outputs = record.get("outputs")
            if not isinstance(outputs, list) or not outputs or not all(
                isinstance(answer, str) and answer for answer in outputs
            ):
                raise ValueError(f"line {line_number}: RULER record needs non-empty outputs")
            yield line_number, record
            count += 1


@torch.no_grad()
def _run_model(
    model,
    tokenizer,
    records: list[tuple[int, dict]],
    device: torch.device,
    max_new_tokens: int,
    *,
    qcc: bool = False,
) -> list[dict]:
    results: list[dict] = []
    for line_number, record in records:
        result = {
            "line": line_number,
            "answers": record["outputs"],
            "length_chars": len(record["input"]),
        }
        try:
            # Each RULER record is an independent serving request.  The
            # retrofit owns its history outside Transformers' cache, so the
            # request boundary must be explicit for every record.
            if qcc:
                reset_hf_qcc_cache(model, batch_size=1)
            encoded = tokenizer(record["input"], return_tensors="pt", add_special_tokens=False)
            encoded = {key: value.to(device) for key, value in encoded.items()}
            result["tokens"] = int(encoded["input_ids"].shape[-1])
            result["task"] = str(
                record.get("task", record.get("task_name", record.get("type", "unknown")))
            )
            result["length_bucket"] = length_bucket(result["tokens"])
            generated = model.generate(
                **encoded,
                max_new_tokens=max_new_tokens,
                do_sample=False,
                use_cache=True,
            )
            continuation = generated[0, encoded["input_ids"].shape[-1] :]
            text = tokenizer.decode(continuation, skip_special_tokens=True)
            result["prediction"] = text
            result["correct"] = any(answer in text for answer in record["outputs"])
        except Exception as exc:  # record execution failures for auditability
            result["correct"] = False
            result["error"] = f"{type(exc).__name__}: {exc}"
        results.append(result)
    return results


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", required=True)
    parser.add_argument("--ruler-jsonl", type=Path, required=True)
    parser.add_argument("--max-examples", type=int, default=None)
    parser.add_argument("--max-new-tokens", type=int, default=32)
    parser.add_argument("--run-id", default=None)
    parser.add_argument(
        "--min-native-context", type=int, default=None,
        help="require the checkpoint to natively declare at least this many tokens",
    )
    parser.add_argument("--dtype", choices=("auto", "float16", "bfloat16", "float32"), default="auto")
    parser.add_argument("--load-in-4bit", action="store_true", help="load the real checkpoint through bitsandbytes NF4")
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--window-size", type=int, default=128)
    parser.add_argument("--num-codes", type=int, default=64)
    parser.add_argument("--adapter", type=Path, default=None)
    parser.add_argument("--exact-num-sets", type=int, default=128)
    parser.add_argument("--exact-ways", type=int, default=4)
    parser.add_argument("--exact-probe-sets", type=int, default=None)
    parser.add_argument(
        "--archive-position-invariant",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="use raw Q/K for archive addressing while local attention keeps RoPE",
    )
    parser.add_argument("--kv-head-policy", choices=("reject", "repeat"), default="reject")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--trust-remote-code", action="store_true")
    args = parser.parse_args()
    if args.max_new_tokens <= 0:
        raise ValueError("max-new-tokens must be positive")
    records = list(_records(args.ruler_jsonl, args.max_examples))
    if not records:
        raise ValueError("RULER JSONL contains no records")
    try:
        from transformers import AutoModelForCausalLM, AutoTokenizer
    except ImportError as exc:  # pragma: no cover
        raise SystemExit("install qcc-transformer[hf] to run this benchmark") from exc
    device = torch.device(args.device)
    dtype = None if args.dtype == "auto" else {
        "float16": torch.float16,
        "bfloat16": torch.bfloat16,
        "float32": torch.float32,
    }[args.dtype]
    common = {"trust_remote_code": args.trust_remote_code}
    tokenizer = AutoTokenizer.from_pretrained(args.model, **common)
    baseline = load_hf_causal_lm(
        args.model,
        dtype=dtype,
        device=device,
        trust_remote_code=args.trust_remote_code,
        load_in_4bit=args.load_in_4bit,
    )
    model_device = model_input_device(baseline, device)
    native_context_tokens = native_context(baseline.config)
    if args.min_native_context is not None and (
        native_context_tokens is None or native_context_tokens < args.min_native_context
    ):
        raise RuntimeError(
            f"model native context {native_context_tokens} is below requested "
            f"{args.min_native_context}"
        )
    baseline_results = _run_model(
        baseline, tokenizer, records, model_device, args.max_new_tokens, qcc=False
    )
    del baseline
    gc.collect()
    if device.type == "cuda":
        torch.cuda.empty_cache()
    patched = load_hf_causal_lm(
        args.model,
        dtype=dtype,
        device=device,
        trust_remote_code=args.trust_remote_code,
        load_in_4bit=args.load_in_4bit,
    )
    patched_device = model_input_device(patched, device)
    if args.adapter is None:
        replaced = patch_hf_model(
            patched,
            window_size=args.window_size,
            num_codes=args.num_codes,
            archive_position_invariant=args.archive_position_invariant,
            kv_head_policy=args.kv_head_policy,
        )
    else:
        replaced = load_hybrid_retrofit_adapter(
            patched,
            args.adapter,
            hybrid_kwargs={
                "exact_num_sets": args.exact_num_sets,
                "exact_ways": args.exact_ways,
                "exact_probe_sets": args.exact_probe_sets,
            },
            window_size=args.window_size,
            num_codes=args.num_codes,
            archive_position_invariant=args.archive_position_invariant,
            kv_head_policy=args.kv_head_policy,
        )
        enable_qkv_only_deployment_profile(patched)
    qcc_results = _run_model(
        patched, tokenizer, records, patched_device, args.max_new_tokens, qcc=True
    )
    baseline_correct = sum(bool(item["correct"]) for item in baseline_results)
    qcc_correct = sum(bool(item["correct"]) for item in qcc_results)
    baseline_by_line = {item["line"]: item for item in baseline_results}
    qcc_by_line = {item["line"]: item for item in qcc_results}

    def paired_ratios(field: str) -> dict[str, float]:
        full_counts: dict[str, list[int]] = {}
        qcc_counts: dict[str, list[int]] = {}
        for line, full_row in baseline_by_line.items():
            qcc_row = qcc_by_line.get(line)
            if qcc_row is None:
                raise RuntimeError(f"missing paired QCC RULER record for line {line}")
            key = full_row.get(field)
            if key is None:
                key = qcc_row.get(field)
            key = str(key if key is not None else "unknown")
            full_counts.setdefault(key, [0, 0])
            qcc_counts.setdefault(key, [0, 0])
            full_counts[key][0] += 1
            full_counts[key][1] += int(bool(full_row.get("correct")))
            qcc_counts[key][1] += int(bool(qcc_row.get("correct")))
        ratios: dict[str, float] = {}
        for key, (count, correct) in full_counts.items():
            if correct <= 0:
                ratios[key] = 0.0
            else:
                ratios[key] = (qcc_counts[key][1] / count) / (correct / count)
        return ratios

    task_ratios = {
        **{f"task:{key}": value for key, value in paired_ratios("task").items()},
        **{
            f"length:{key}": value
            for key, value in paired_ratios("length_bucket").items()
        },
    }
    result = {
        "schema": "qcc-ruler-v1",
        "benchmark": "ruler",
        "model": args.model,
        "model_id": args.model,
        "run_id": args.run_id,
        "matched_full_kv": True,
        "real_model": True,
        "synthetic": False,
        "official": True,
        "qcc_only": False,
        "qcc_score": qcc_correct / len(records),
        "full_kv_score": baseline_correct / len(records),
        "task_ratios": task_ratios,
        "quality_score": qcc_correct / len(records),
        "native_context_tokens": native_context_tokens,
        "records": len(records),
        "patched_layers": replaced,
        "baseline_full_kv": {
            "correct": baseline_correct,
            "accuracy": baseline_correct / len(records),
            "records": baseline_results,
        },
        "qcc_retrofit": {
            "correct": qcc_correct,
            "accuracy": qcc_correct / len(records),
            "records": qcc_results,
        },
        "note": "Official RULER record scoring; generation failures count as incorrect and no quality claim is made beyond this split.",
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps({k: result[k] for k in ("model", "records", "patched_layers", "baseline_full_kv", "qcc_retrofit") if k != "baseline_full_kv" or True}, indent=2)[:4000])


if __name__ == "__main__":
    main()
